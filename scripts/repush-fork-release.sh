#!/usr/bin/env bash
#
# repush-fork-release.sh [VERSION] [--execute] [--workflow] [-m MESSAGE]
#
# Convenience wrapper for the common fork-release iteration loop:
#   1. commit current changes on release-vVERSION
#   2. force-move local vVERSION tag to HEAD
#   3. push release-vVERSION and vVERSION to origin
#   4. optionally trigger fork-release.yml against the tag
#
# Dry-run is the default. Pass --execute to actually run commands.

set -euo pipefail

VERSION="1.15.1"
EXECUTE=0
RUN_WORKFLOW=0
DO_COMMIT=1
COMMIT_MESSAGE=""
ORIGIN_REMOTE="${ORIGIN_REMOTE:-origin}"
WORKFLOW="${WORKFLOW:-fork-release.yml}"

usage() {
  cat <<'EOF'
usage: scripts/repush-fork-release.sh [VERSION] [options]

Options:
  --execute          run the git/gh commands (default is dry-run)
  --workflow         trigger fork-release.yml after pushing
  --no-commit        push/tag current HEAD without committing dirty changes
  -m, --message MSG  commit message (default: "Update fork release vVERSION")
  -h, --help         show this help

Examples:
  scripts/repush-fork-release.sh
  scripts/repush-fork-release.sh 1.15.1 --execute -m "Fix Windows log filename"
  scripts/repush-fork-release.sh 1.15.1 --execute --workflow
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --execute)
      EXECUTE=1
      shift
      ;;
    --workflow)
      RUN_WORKFLOW=1
      shift
      ;;
    --no-commit)
      DO_COMMIT=0
      shift
      ;;
    -m|--message)
      COMMIT_MESSAGE="${2:?missing message for $1}"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    -*)
      echo "ERROR: unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
    *)
      VERSION="${1#v}"
      shift
      ;;
  esac
done

TAG="v${VERSION}"
BRANCH="release-${TAG}"
COMMIT_MESSAGE="${COMMIT_MESSAGE:-Update fork release ${TAG}}"

run() {
  printf '+'
  printf ' %q' "$@"
  printf '\n'
  if [ "${EXECUTE}" -eq 1 ]; then
    "$@"
  fi
}

current_branch="$(git branch --show-current)"
if [ "${current_branch}" != "${BRANCH}" ]; then
  echo "ERROR: expected to be on ${BRANCH}, currently on ${current_branch:-detached HEAD}" >&2
  exit 1
fi

if ! git remote get-url "${ORIGIN_REMOTE}" >/dev/null 2>&1; then
  echo "ERROR: remote '${ORIGIN_REMOTE}' does not exist" >&2
  exit 1
fi

origin_url="$(git remote get-url "${ORIGIN_REMOTE}")"
fork_repo="$(printf '%s' "${origin_url}" \
  | sed -E 's#^git@[^:]+:##; s#^https?://[^/]+/##; s/\.git$//')"

mkdir -p .release-push
plan_file=".release-push/${TAG}-last-plan.sh"
{
  echo "# Generated by scripts/repush-fork-release.sh"
  echo "# $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  echo "# branch=${BRANCH}"
  echo "# tag=${TAG}"
  echo "# repo=${fork_repo}"
} > "${plan_file}"

echo "==> release branch: ${BRANCH}"
echo "==> release tag:    ${TAG}"
echo "==> fork repo:      ${fork_repo}"
if [ "${EXECUTE}" -eq 0 ]; then
  echo "==> dry-run only; pass --execute to run"
fi

if [ "${DO_COMMIT}" -eq 1 ]; then
  if ! git diff --quiet || ! git diff --cached --quiet; then
    run git add -A
    run git commit -m "${COMMIT_MESSAGE}"
  else
    echo "==> no working tree changes to commit"
  fi
else
  if ! git diff --quiet || ! git diff --cached --quiet; then
    echo "ERROR: --no-commit was set, but the working tree is dirty" >&2
    git status --short >&2
    exit 1
  fi
fi

run git tag -f -a "${TAG}" -m "Fork release of ziti-edge-tunnel ${VERSION}"
run git push "${ORIGIN_REMOTE}" "${BRANCH}"
run git push --force "${ORIGIN_REMOTE}" "${TAG}"

if [ "${RUN_WORKFLOW}" -eq 1 ]; then
  run gh workflow run "${WORKFLOW}" --repo "${fork_repo}" --ref "${TAG}"
else
  echo "==> workflow not triggered; add --workflow to run ${WORKFLOW} on ${TAG}"
fi

cat >> "${plan_file}" <<EOF
git tag -f -a ${TAG} -m "Fork release of ziti-edge-tunnel ${VERSION}"
git push ${ORIGIN_REMOTE} ${BRANCH}
git push --force ${ORIGIN_REMOTE} ${TAG}
gh workflow run ${WORKFLOW} --repo ${fork_repo} --ref ${TAG}
EOF

echo "==> wrote last command plan to ${plan_file}"
